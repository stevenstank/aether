// The powers of ten in rt/pow10.s: those Dragonbox reads for float64 and
// float32 (k from -292 to 326, D-032).
const pow10First, pow10Last = -292, 326

// pow10Source returns rt/pow10.s. Entry k-pow10First is the 128-bit
// mantissa of 10**k as go1.26.1's internal/strconv pow10Tab holds it:
// 10**k scaled by a power of two into [2**127, 2**128) and truncated,
// stored high word first.
func pow10Source() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, `# Code generated by TestPow10Table (internal/amd64/float_test.go); DO NOT EDIT.
#
# aether.pow10 holds the 128-bit mantissas of 10**k for k from %d to %d,
# high word first, for aether.printfloat64 and aether.printfloat32
# (float.s): 10**k scaled by a power of two into [2**127, 2**128) and
# truncated.

	.section	.rodata
	.p2align	4
	.globl	aether.pow10
	.type	aether.pow10, @object
	.size	aether.pow10, %d
aether.pow10:
`, pow10First, pow10Last, 16*(pow10Last-pow10First+1))
	mask := new(big.Int).SetUint64(math.MaxUint64)
	for k := pow10First; k <= pow10Last; k++ {
		p := new(big.Int).Exp(big.NewInt(10), big.NewInt(int64(max(k, -k))), nil)
		var d *big.Int
		switch n := p.BitLen(); {
		case k < 0:
			// 10**k is not a power of two, so 2**(127+n) / 10**-k lies
			// strictly between 2**127 and 2**128.
			d = new(big.Int).Quo(new(big.Int).Lsh(big.NewInt(1), uint(127+n)), p)
		case n <= 128:
			d = new(big.Int).Lsh(p, uint(128-n))
		default:
			d = new(big.Int).Rsh(p, uint(n-128))
		}
		hi := new(big.Int).Rsh(d, 64).Uint64()
		lo := new(big.Int).And(d, mask).Uint64()
		fmt.Fprintf(&b, "\t.quad\t%#016x, %#016x\t# 1e%d\n", hi, lo, k)
	}
	b.WriteString("\n\t.section\t.note.GNU-stack,\"\",@progbits\n")
	return b.Bytes()
}

// TestPow10Table checks that rt/pow10.s is pow10Source's output; -update
// rewrites it.
func TestPow10Table(t *testing.T) {
	want := pow10Source()
	if *update {
		if err := os.WriteFile("rt/pow10.s", want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile("rt/pow10.s")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Error("rt/pow10.s is stale; run go test ./internal/amd64 -run TestPow10Table -update")
	}
	// Spot checks against go1.26.1's pow10Tab.
	for _, s := range []string{
		"0x8000000000000000, 0x0000000000000000\t# 1e0",
		"0xa000000000000000, 0x0000000000000000\t# 1e1",
		"0xcccccccccccccccc, 0xcccccccccccccccc\t# 1e-1",
	} {
		if !bytes.Contains(got, []byte(s)) {
			t.Errorf("rt/pow10.s has no entry %q", s)
		}
	}
}

// floatValues64 returns float64 bit patterns that exercise every path of
// the formatter: the special values, every binary exponent, powers of two
// (Dragonbox's boundary case) and of ten with their neighbors, integers,
// short decimals, and random bit patterns.
func floatValues64() []uint64 {
	r := rand.New(rand.NewPCG(1, 2))
	var v []uint64
	add := func(f float64) { v = append(v, math.Float64bits(f), math.Float64bits(-f)) }
	for _, f := range []float64{0, 1, 0.1, 0.5, 2.5, 1e6, 1e21, 123456, 1234567, 1e-4, 1e-5, 5e-324, math.MaxFloat64,
		math.SmallestNonzeroFloat64, 0x1p-1022, 0x1p-1022 - 5e-324, math.Inf(1), 1.0 / 3, 2.0 / 3, 9007199254740993} {
		add(f)
	}
	v = append(v, 0x7ff8000000000000, 0xfff8000000000001, 0x7ff0000000000001)
	for e := uint64(0); e < 2047; e++ {
		for _, m := range []uint64{0, 1, 2, 3, 1<<52 - 1, 1 << 51, r.Uint64() & (1<<52 - 1)} {
			v = append(v, e<<52|m, 1<<63|e<<52|m)
		}
	}
	for k := -324; k <= 308; k++ {
		f, _ := strconv.ParseFloat("1e"+strconv.Itoa(k), 64)
		add(f)
		add(math.Nextafter(f, 0))
		add(math.Nextafter(f, math.Inf(1)))
	}
	for i := range 2000 {
		add(float64(i))
	}
	for range 50000 {
		digits := fmt.Sprintf("%017d", r.Uint64N(1e17))[:1+r.IntN(17)]
		f, _ := strconv.ParseFloat(digits+"e"+strconv.Itoa(r.IntN(660)-340), 64)
		add(f)
	}
	for range 200000 {
		v = append(v, r.Uint64())
	}
	return v
}

// floatValues32 is floatValues64 for float32, in the low 32 bits.
func floatValues32() []uint64 {
	r := rand.New(rand.NewPCG(3, 4))
	var v []uint64
	add := func(f float32) { v = append(v, uint64(math.Float32bits(f)), uint64(math.Float32bits(-f))) }
	for _, f := range []float32{0, 1, 0.1, 16777216, 16777217, 1e6, 1e-5, math.MaxFloat32, math.SmallestNonzeroFloat32,
		0x1p-126, float32(math.Inf(1)), 1.0 / 3} {
		add(f)
	}
	v = append(v, 0x7fc00000, 0xffc00001, 0x7f800001)
	for e := uint64(0); e < 255; e++ {
		for _, m := range []uint64{0, 1, 2, 3, 1<<23 - 1, 1 << 22, r.Uint64() & (1<<23 - 1)} {
			v = append(v, e<<23|m, 1<<31|e<<23|m)
		}
	}
	for k := -46; k <= 39; k++ {
		f64, _ := strconv.ParseFloat("1e"+strconv.Itoa(k), 32)
		f := float32(f64)
		add(f)
		add(math.Nextafter32(f, 0))
		add(math.Nextafter32(f, float32(math.Inf(1))))
	}
	for i := range 2000 {
		add(float32(i))
	}
	for range 50000 {
		digits := fmt.Sprintf("%09d", r.Uint64N(1e9))[:1+r.IntN(9)]
		f, _ := strconv.ParseFloat(digits+"e"+strconv.Itoa(r.IntN(90)-50), 32)
		add(float32(f))
	}
	for range 200000 {
		v = append(v, uint64(r.Uint32()))
	}
	return v
}

// floatHarness prints each value of v64 with aether.printfloat64 and each
// of v32 with aether.printfloat32, one per line.
func floatHarness(v64, v32 []uint64) string {
	var b strings.Builder
	b.WriteString("\t.text\n\t.globl\tmain.main\nmain.main:\n\tpushq\t%rbp\n\tmovq\t%rsp, %rbp\n\tpushq\t%rbx\n\tpushq\t%r12\n")
	for i, c := range []struct {
		sym string
		n   int
	}{{"aether.printfloat64", len(v64)}, {"aether.printfloat32", len(v32)}} {
		fmt.Fprintf(&b, "\tleaq\tvals%d(%%rip), %%rbx\n\tmovq\t$%d, %%r12\n", i, c.n)
		fmt.Fprintf(&b, "%d:\tmovq\t(%%rbx), %%rdi\n\tcall\t%s\n\tcall\taether.printnl\n\taddq\t$8, %%rbx\n\tdecq\t%%r12\n\tjnz\t%db\n", i+1, c.sym, i+1)
	}
	b.WriteString("\tpopq\t%r12\n\tpopq\t%rbx\n\tpopq\t%rbp\n\tret\n\t.section\t.rodata\n\t.p2align\t3\n")
	for i, v := range [][]uint64{v64, v32} {
		fmt.Fprintf(&b, "vals%d:\n", i)
		for _, x := range v {
			fmt.Fprintf(&b, "\t.quad\t%#x\n", x)
		}
	}
	return b.String() + mainStack(48)
}

// TestPrintFloat runs the runtime's float formatting natively on about half
// a million values and requires exactly what gc's print writes for each:
// strconv's shortest 'g' format, which runtime.printfloat64 and
// printfloat32 use in go1.26.1.
func TestPrintFloat(t *testing.T) {
	v64, v32 := floatValues64(), floatValues32()
	exe := link(t, t.TempDir(), withRuntime([]byte(floatHarness(v64, v32))))
	got, code := execute(t, exe, nil)
	if code != 0 {
		t.Fatalf("exit %d", code)
	}
	var want strings.Builder
	for _, x := range v64 {
		want.WriteString(strconv.FormatFloat(math.Float64frombits(x), 'g', -1, 64) + "\n")
	}
	for _, x := range v32 {
		want.WriteString(strconv.FormatFloat(float64(math.Float32frombits(uint32(x))), 'g', -1, 32) + "\n")
	}
	gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want.String(), "\n")
	if len(gotLines) != len(wantLines) {
		t.Fatalf("%d lines, want %d", len(gotLines), len(wantLines))
	}
	bad := 0
	for i := range wantLines {
		if gotLines[i] != wantLines[i] {
			if bad++; bad <= 20 {
				x, kind := uint64(0), "float32"
				if i < len(v64) {
					x, kind = v64[i], "float64"
				} else if i-len(v64) < len(v32) {
					x = v32[i-len(v64)]
				}
				t.Errorf("%s %#x: got %q, want %q", kind, x, gotLines[i], wantLines[i])
			}
		}
	}
	if bad > 0 {
		t.Errorf("%d of %d values differ", bad, len(wantLines)-1)
	}
	// The format itself, independent of the strconv the test runs with
	// (observed from gc-built go1.26.1 binaries, D-032).
	for _, s := range []string{"\n0\n-0\n1\n-1\n0.1\n-0.1\n0.5\n", "\n1e+06\n-1e+06\n1e+21\n", "\n123456\n-123456\n1.234567e+06\n",
		"\n0.0001\n-0.0001\n1e-05\n", "\n5e-324\n", "\n1.7976931348623157e+308\n", "\n+Inf\n-Inf\n", "\nNaN\nNaN\nNaN\n",
		"\n1.6777216e+07\n", "\n0.33333334\n"} {
		if !strings.Contains("\n"+got, s) {
			t.Errorf("output lacks %q", s)
		}
	}
}

// Float edge values: zeros, NaN, infinities, the extremes, values at the
// integer conversion boundaries, and ties for rounding.
var (
	edges64 = []float64{0, math.Copysign(0, -1), 1, -1, 0.5, -2.5, 3.5, 0.1, 1.0 / 3, math.MaxFloat64, -math.MaxFloat64,
		math.SmallestNonzeroFloat64, 0x1p-1022, math.Inf(1), math.Inf(-1), math.NaN(), 0x1p63, 0x1p64, -0x1p63, 9.3e18,
		-9.3e18, 3e9, -3e9, 4.5e9, 2147483647.9, -2147483648.9, 70000, -70000, 300, -300, 255.9, 1e300, 16777217}
	edges32 = []float32{0, float32(math.Copysign(0, -1)), 1, -1, 0.5, -2.5, 0.1, 1.0 / 3, math.MaxFloat32, -math.MaxFloat32,
		math.SmallestNonzeroFloat32, float32(math.Inf(1)), float32(math.Inf(-1)), float32(math.NaN()), 0x1p63, 0x1p64,
		3e9, -3e9, 70000, -300, 16777216}
	intEdges = []int64{0, 1, -1, 127, -128, 255, 65535, math.MaxInt32, math.MinInt32, math.MaxUint32, 1<<53 + 1,
		1<<62 + 1<<9 + 1, math.MaxInt64, math.MinInt64}
	floatIntTypes = []ir.Type{ir.I8, ir.I16, ir.I32, ir.I64, ir.U8, ir.U16, ir.U32, ir.U64}
)

// floatProgram returns a program that applies every float operation to the
// edge values and prints the results. Each first operand has its own
// function, keeping each under the allocator's bound; mix takes seven
// arguments, so ABI-R1 passes one on the stack, and returns a tuple.
func floatProgram() *ir.Program {
	p := &ir.Program{}
	mix := p.NewFunc("mix", "p.go", p1)
	mix.Params = []ir.Type{ir.F64, ir.F32, ir.F64, ir.F32, ir.F64, ir.F32, ir.F64}
	mix.Results = []ir.Type{ir.F64, ir.F32}
	{
		b := mix.Entry()
		var ps []*ir.Instr
		for i := range mix.Params {
			ps = append(ps, mix.Param(b, i, p1))
		}
		r0 := mix.Float(b, ir.FAdd, p1, mix.Float(b, ir.FMul, p1, ps[0], ps[2]), ps[6])
		r1 := mix.Float(b, ir.FSub, p1, mix.Float(b, ir.FDiv, p1, ps[1], ps[3]), mix.Convert(b, ir.FToF, ir.F32, ps[4], p1))
		mix.Println(b, []*ir.Instr{ps[5], mix.Float(b, ir.FNeg, p1, ps[6])}, p1)
		mix.Ret(b, p1, r0, r1)
	}
	main := p.NewFunc("main", "p.go", p1)
	mb := main.Entry()
	test := func(name string, body func(f *ir.Func, b *ir.Block)) {
		f := p.NewFunc(name, "p.go", p1)
		body(f, f.Entry())
		f.Ret(f.Entry(), p1)
		main.Call(mb, f, nil, p1)
	}
	// A value through a slot, so that promotion leaves a constant.
	val := func(f *ir.Func, b *ir.Block, t ir.Type, bits int64) *ir.Instr {
		s := f.NewSlot("x", t, p1)
		f.Store(b, s, f.TypedConst(b, t, bits, p1), p1)
		return f.Load(b, s, p1)
	}
	binary := []ir.Op{ir.FAdd, ir.FSub, ir.FMul, ir.FDiv, ir.FEq, ir.FNe, ir.FLt, ir.FLe, ir.FGt, ir.FGe}
	for i, x := range edges64 {
		test(fmt.Sprintf("d%d", i), func(f *ir.Func, b *ir.Block) {
			xv := val(f, b, ir.F64, int64(math.Float64bits(x)))
			for _, y := range edges64 {
				yv := val(f, b, ir.F64, int64(math.Float64bits(y)))
				var args []*ir.Instr
				for _, op := range binary {
					args = append(args, f.Float(b, op, p1, xv, yv))
				}
				f.Println(b, args, p1)
			}
			args := []*ir.Instr{xv, f.Float(b, ir.FNeg, p1, xv), f.Convert(b, ir.FToF, ir.F32, xv, p1)}
			for _, t := range floatIntTypes {
				args = append(args, f.Convert(b, ir.FToI, t, xv, p1))
			}
			f.Println(b, args, p1)
		})
	}
	for i, x := range edges32 {
		test(fmt.Sprintf("s%d", i), func(f *ir.Func, b *ir.Block) {
			xv := val(f, b, ir.F32, int64(math.Float32bits(x)))
			for _, y := range edges32 {
				yv := val(f, b, ir.F32, int64(math.Float32bits(y)))
				var args []*ir.Instr
				for _, op := range binary {
					args = append(args, f.Float(b, op, p1, xv, yv))
				}
				f.Print(b, args, p1)
				f.Println(b, nil, p1)
			}
			args := []*ir.Instr{f.Float(b, ir.FNeg, p1, xv), f.Convert(b, ir.FToF, ir.F64, xv, p1)}
			for _, t := range floatIntTypes {
				args = append(args, f.Convert(b, ir.FToI, t, xv, p1))
			}
			f.Println(b, args, p1)
		})
	}
	test("ints", func(f *ir.Func, b *ir.Block) {
		for _, t := range floatIntTypes {
			for _, x := range intEdges {
				xv := val(f, b, t, t.Canonical(x))
				f.Println(b, []*ir.Instr{xv, f.Convert(b, ir.IToF, ir.F64, xv, p1), f.Convert(b, ir.IToF, ir.F32, xv, p1)}, p1)
			}
		}
	})
	test("calls", func(f *ir.Func, b *ir.Block) {
		for i := range 4 {
			var args []*ir.Instr
			for j, t := range mix.Params {
				if t == ir.F64 {
					args = append(args, val(f, b, t, int64(math.Float64bits(edges64[(i*7+j)%len(edges64)]))))
				} else {
					args = append(args, val(f, b, t, int64(math.Float32bits(edges32[(i*5+j)%len(edges32)]))))
				}
			}
			call := f.Call(b, mix, args, p1)
			f.Println(b, []*ir.Instr{f.Extract(b, call, 0, p1), f.Extract(b, call, 1, p1)}, p1)
		}
	})
	main.Ret(mb, p1)
	return p
}

// TestNativeFloat runs floatProgram in the interpreter, with the slot-based
// backend, and with aether build's backend (SSA, registers, selection,
// two-address arithmetic, and ABI-R1), and requires identical output. The
// interpreter's results for the edge cases gc decides are checked against
// gc in cmd/aether; here a few are pinned.
func TestNativeFloat(t *testing.T) {
	var want bytes.Buffer
	if code, err := interp.Run(floatProgram(), &want); err != nil || code != 0 {
		t.Fatalf("interpreter: exit %d, %v", code, err)
	}
	for _, s := range []string{
		"\nNaN NaN NaN NaN false true false false false false\n", // NaN with itself
		"\n0 0 -0 NaN true false false true false true\n",        // +0 with -0
		"\n+Inf NaN +Inf NaN true false false true false true\n", // +Inf with itself
		// x, -x, float32(x), and x converted to int8 ... int64 and uint8 ...
		// uint64, as gc-built go1.26.1 binaries print them (D-032).
		"\nNaN NaN NaN 0 0 -2147483648 -9223372036854775808 0 0 0 9223372036854775808\n",
		"\n3e+09 -3e+09 3e+09 0 0 -2147483648 3000000000 0 0 3000000000 3000000000\n",
		"\n-3e+09 3e+09 -3e+09 0 0 -2147483648 -3000000000 0 0 1294967296 18446744070709551616\n",
		"\n-70000 70000 -70000 -112 -4464 -70000 -70000 144 61072 4294897296 18446744073709481616\n",
		"\n9.3e+18 -9.3e+18 9.3e+18 0 0 -2147483648 -9223372036854775808 0 0 0 9300000000000000000\n",
		"\n4.5e+09 -4.5e+09 4.5e+09 0 0 -2147483648 4500000000 0 0 205032704 4500000000\n",
	} {
		if !strings.Contains("\n"+want.String(), s) {
			t.Errorf("interpreter output lacks %q", s)
		}
	}
	slots, err := Emit(floatProgram())
	if err != nil {
		t.Fatal(err)
	}
	prog := floatProgram()
	for _, f := range prog.Funcs {
		if err := ir.Promote(f); err != nil {
			t.Fatal(err)
		}
	}
	regs, err := EmitWith(prog, EmitOptions{Registers: true, Select: true, ABIR1: true, TwoAddress: true, Coalesce: true})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(regs, []byte("%xmm0, %r")) {
		t.Error("no float result is written to a register")
	}
	for name, asm := range map[string][]byte{"slots": slots, "registers": regs} {
		got, code := execute(t, link(t, t.TempDir(), withRuntime(asm)), nil)
		if code != 0 || got != want.String() {
			t.Errorf("%s: exit %d; native output differs from the interpreter's", name, code)
			g, w := strings.Split(got, "\n"), strings.Split(want.String(), "\n")
			for i := range min(len(g), len(w)) {
				if g[i] != w[i] {
					t.Errorf("line %d: native %q, interpreter %q", i+1, g[i], w[i])
					break
				}
			}
		}
	}
}
